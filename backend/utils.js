/**
 * Преобразует строку с разделителями-запятыми в массив строк.
 * Возвращает пустой массив, если входное значение не является строкой.
 * @param {string | null | undefined} str - Входная строка.
 * @returns {string[]} Массив очищенных строк.
 */
const stringToArray = (str) => {
    // Проверка, что str является непустой строкой.
    // Если нет, возвращаем пустой массив.
    if (typeof str !== 'string' || str.trim() === '') {
        return [];
    }
    // Разделяем строку по запятой, обрезаем пробелы у каждого элемента.
    return str.split(',').map(s => s.trim()).filter(s => s.length > 0);
};

